成绩=[]
数量=0
while True:
    x=input("请输入一个成绩(直接输入回车退出)：")
    if x=='':
        break
    成绩.append(int(x))
    数量+=1
最高分=max(成绩)
最低分=min(成绩)
平均分=sum(成绩)/数量
lst=sorted(成绩)
if 数量%2!=0:
    中位数=lst[数量//2]
else:
    中位数=(lst[数量//2]+lst[数量//2-1])/2
print(f"总共输入{数量}个成绩，\n最高分:{最高分}\n最低分:{最低分}\n平均分:{平均分:.2f}\n中位数:{中位数:.2f}")
